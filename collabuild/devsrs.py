@dataclass
class SRSBlueprint:
    """Structured requirements extracted from a drafted SRS document."""

    title: str = "Generated Application"
    description: str = ""
    actors: list[str] = field(default_factory=list)
    functional_requirements: list[str] = field(default_factory=list)
    nonfunctional_requirements: list[str] = field(default_factory=list)
    modules: list[str] = field(default_factory=list)
    features: list[str] = field(default_factory=list)
    tech_stack: list[str] = field(default_factory=list)
    api_endpoints: list[str] = field(default_factory=list)


# ── SRS parsing ──────────────────────────────────────────────────────────────

_SECTION_RE = re.compile(r"^\s*(#{1,6}\s+|(?:FR|NF)\s*-?\s*\d+|[-*]\s+)")


def _slugify(name: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return slug or "capability"


def _section_lines(text: str, *titles: str) -> list[str]:
    """Return stripped lines under the first markdown heading matching any title."""
    capture = False
    out: list[str] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            if capture:
                break
            capture = any(t.lower() in line.lower() for t in titles)
            continue
        if capture:
            out.append(line)
    return out


def _bullets(lines: list[str]) -> list[str]:
    items = []
    for line in lines:
        m = re.match(r"^\s*[-*]\s+(.+)$", line)
        if m:
            items.append(m.group(1).strip())
    return items


def _numbered(lines: list[str], pattern: str) -> list[str]:
    found = []
    for line in lines:
        if re.search(pattern, line, re.I):
            cleaned = re.sub(r"^[-*\d.\s:]+", "", line).strip()
            if cleaned and cleaned not in found:
                found.append(cleaned)
    return found


def parse_srs(text: str) -> SRSBlueprint:
    """Parse an IEEE 830-style SRS markdown document into a SRSBlueprint."""
    bp = SRSBlueprint()

    m = re.search(r"^\s*#\s+(.+)$", text, re.M)
    if m:
        bp.title = m.group(1).strip()
    m = re.search(r"Purpose[:\-]\s*(.+)", text, re.I)
    if m:
        bp.description = m.group(1).strip()

    bp.functional_requirements = _numbered(
        text.splitlines(), r"^\s*(?:- )?FR\s*-?\s*\d+"
    )
    bp.nonfunctional_requirements = _numbered(
        text.splitlines(), r"^\s*(?:- )?NF\s*-?\s*\d+"
    )

    bp.features = _bullets(_section_lines(text, "system features", "features", "modules"))
    bp.tech_stack = _bullets(
        _section_lines(text, "technology", "tech stack", "external interfaces")
    )

    for line in text.splitlines():
        if re.search(r"(GET|POST|PUT|DELETE|PATCH)\s+/", line, re.I):
            ep = re.sub(r"^[-*\s]+", "", line).strip()
            if ep not in bp.api_endpoints:
                bp.api_endpoints.append(ep)

    for line in _bullets(_section_lines(text, "user characteristics", "actors")):
        bp.actors.append(line)

    names = bp.features or bp.modules or bp.functional_requirements or ["process"]
    bp.modules = [n for n in names if not n.lower().startswith(("fr-", "nf-"))]
    bp.features = bp.features or bp.modules

    if not bp.description:
        bp.description = f"A system built from the SRS for {bp.title}."

    return bp


# ── Template assembly ────────────────────────────────────────────────────────

def _core_entries(blueprint: SRSBlueprint) -> str:
    names = blueprint.features or ["process"]
    lines = []
    for name in names:
        lines.append(f'    "{_slugify(name)}": _default_impl("{name}"),')
    return "\n".join(lines)


def _mcp_tools(blueprint: SRSBlueprint) -> str:
    names = blueprint.features or ["process"]
    tools = []
    for name in names[:25]:
        slug = _slugify(name)
        tools.append(
            f'        {{"name": "{slug}", "description": "{name}", '
            f'"inputSchema": {{"type": "object", "properties": {{}}, "additionalProperties": True}}}},'
        )
    return "\n".join(tools)


def _file_tree(paths: list[str]) -> str:
    return "\n".join(f"├── {p}" for p in paths)


def _ctx(blueprint: SRSBlueprint, package: str, target: str, paths: list[str],
         quickstart: str) -> dict:
    caps = [str(_slugify(n)) for n in (blueprint.features or ["process"])]
    return {
        "TITLE": blueprint.title,
        "PACKAGE": package,
        "DESCRIPTION": blueprint.description,
        "FEATURES": "\n".join(f"- {n}" for n in (blueprint.features or ["process"])),
        "CORE_ENTRIES": _core_entries(blueprint),
        "MCP_TOOLS": _mcp_tools(blueprint),
        "FIRST_CAP": caps[0] if caps else "process",
        "QUICKSTART": quickstart,
        "FILE_TREE": _file_tree(paths),
    }


def files_for(blueprint: SRSBlueprint, target: str) -> dict[str, str]:
    """Return {relative_path: content} for a fully runnable scaffold."""
    if target not in SUPPORTED_TARGETS:
        raise ValueError(f"unsupported target {target!r}; expected one of {SUPPORTED_TARGETS}")

    package = _slugify(blueprint.title) or "generated_app"
    if target == "cli":
        files = {
            "core.py": CORE_PY,
            "agents.py": AGENTS_PY,
            "main.py": CLI_MAIN,
            "tests/test_core.py": CORE_TEST,
            "requirements.txt": REQUIREMENTS["cli"],
            ".env.example": ENV_EXAMPLE,
            "README.md": PACKAGE_README,
        }
        quickstart = "python main.py --list"
    elif target == "web":
        files = {
            "main.py": WEB_MAIN,
            "core.py": CORE_PY,
            "agents.py": AGENTS_PY,
            "static/index.html": WEB_INDEX,
            "tests/test_core.py": CORE_TEST,
            "Dockerfile": DOCKERFILE,
            "requirements.txt": REQUIREMENTS["web"],
            ".env.example": ENV_EXAMPLE,
            "README.md": PACKAGE_README,
        }
        quickstart = "pip install -r requirements.txt && uvicorn main:app --reload"
    else:  # mcp
        files = {
            "server.py": MCP_SERVER,
            "core.py": CORE_PY,
            "agents.py": AGENTS_PY,
            "tests/test_core.py": CORE_TEST,
            "tests/test_mcp.py": MCP_TEST,
            "requirements.txt": REQUIREMENTS["mcp"],
            ".env.example": ENV_EXAMPLE,
            "README.md": PACKAGE_README,
        }
        quickstart = "python server.py"

    ctx = _ctx(blueprint, package, target, list(files), quickstart)
    rendered = {
        rel: (tmpl.substitute(ctx) if isinstance(tmpl, Template) else tmpl)
        for rel, tmpl in files.items()
    }
    rendered["README.md"] += "\nGenerated by Collabuild DevSRS.\n"
    return rendered


# ── Builder ──────────────────────────────────────────────────────────────────

class DevSRS:
    """Build a runnable application from a drafted SRS document."""

    def __init__(self, provider=None, target: str = "cli", model: str = "",
                 output_dir: str = "generated_app", max_tokens: int = 4096):
        if target not in SUPPORTED_TARGETS:
            raise ValueError(f"unsupported target {target!r}; expected one of {SUPPORTED_TARGETS}")
        self.provider = provider
        self.target = target
        self.model = model
        self.output_dir = Path(output_dir)
        self.max_tokens = max_tokens

    def _llm_available(self) -> bool:
        if self.provider is None:
            return False
        try:
            from .providers import DevProvider
            return not isinstance(self.provider, DevProvider)
        except ImportError:
            return True

    def _generate_core_with_llm(self, blueprint: SRSBlueprint) -> str:
        """Ask the LLM to write the core.py implementation from the SRS."""
        sys_prompt = (
            "You are an expert application developer. Write production-grade "
            "stdlib-only Python from a software requirements specification."
        )
        reqs = "\n".join(f"- {r}" for r in blueprint.functional_requirements[:15])
        features = "\n".join(f"- {n}" for n in blueprint.features[:15])
        user_prompt = (
            f"Write the complete implementation of `core.py` for this system.\n\n"
            f"Title: {blueprint.title}\n"
            f"Features/modules:\n{features}\n"
            f"Functional requirements:\n{reqs}\n\n"
            f"Requirements:\n"
            f"- Provide `CORE` dict mapping capability name -> callable(args: dict|None) -> dict\n"
            f"- Provide `run_capability(name, args)` and `capabilities()` functions\n"
            f"- stdlib only, no external imports\n"
            f"- Return ONLY the python code in a ```python fenced block."
        )
        resp = self.provider.chat(
            self.model,
            messages=[
                {"role": "system", "content": sys_prompt},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0.2,
            max_tokens=self.max_tokens,
        )
        m = re.search(r"```python\s*\n(.*?)```", resp, re.DOTALL)
        code = m.group(1).strip() if m else resp.strip()
        if code.startswith("Error:"):
            return ""
        return code

    def _smoke_test(self, files: dict[str, str]) -> list[dict]:
        """Syntax-check every generated .py file (no execution)."""
        import py_compile

        results = []
        for rel in files:
            if not rel.endswith(".py"):
                continue
            path = self.output_dir / rel
            try:
                py_compile.compile(str(path), doraise=True)
                results.append({"file": rel, "ok": True})
            except Exception as exc:  # noqa: BLE001
                results.append({"file": rel, "ok": False, "error": str(exc)})
        return results

    def build(self, srs_text: str, use_llm: bool = True) -> dict:
        """Build the application. Returns a structured result dict."""
        blueprint = parse_srs(srs_text)
        files = files_for(blueprint, self.target)

        if use_llm and self._llm_available():
            try:
                code = self._generate_core_with_llm(blueprint)
                if code:
                    files["core.py"] = code
            except Exception as exc:  # noqa: BLE001
                log.warning("LLM codegen failed, using template: %s", exc)

        self.output_dir.mkdir(parents=True, exist_ok=True)
        written = []
        for rel, content in files.items():
            path = self.output_dir / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            written.append(rel)

        smoke = self._smoke_test(files)

        return {
            "target": self.target,
            "output_dir": str(self.output_dir),
            "files": written,
            "smoke_test": smoke,
            "smoke_ok": all(r["ok"] for r in smoke),
            "blueprint": {
                "title": blueprint.title,
                "description": blueprint.description,
                "actors": blueprint.actors,
                "features": blueprint.features,
                "functional_requirements": blueprint.functional_requirements,
                "nonfunctional_requirements": blueprint.nonfunctional_requirements,
                "tech_stack": blueprint.tech_stack,
                "api_endpoints": blueprint.api_endpoints,
            },
        }
