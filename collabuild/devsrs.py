CLI_MAIN = Template("""\"\"\"
$TITLE — command line interface.

Generated by DevSRS from a drafted SRS. Run any capability through the
agent layer or directly:

    python main.py --list
    python main.py $FIRST_CAP --args '{"key": "value"}'
    python main.py $FIRST_CAP --agent planner
\"\"\"

from __future__ import annotations

import argparse
import json
import sys

import agents
import core


def build_parser() -> argparse.ArgumentParser:
    caps = core.capabilities()
    parser = argparse.ArgumentParser(prog="$PACKAGE", description="$DESCRIPTION")
    parser.add_argument("capability", nargs="?", help="capability to run: " + ", ".join(caps))
    parser.add_argument("--args", default="{}", help='JSON args, e.g. {"path": "x.pdf"}')
    parser.add_argument("--list", action="store_true", help="list available capabilities")
    parser.add_argument("--agent", default="", help="route through a named agent (see agents.py)")
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.list:
        print("Capabilities:")
        for cap in core.capabilities():
            print(f"  - {cap}")
        return 0

    if not args.capability:
        parser.print_help()
        return 1

    try:
        payload = json.loads(args.args)
    except json.JSONDecodeError:
        print(f"error: --args must be valid JSON, got: {args.args!r}", file=sys.stderr)
        return 2

    if args.agent:
        tools = [agents.Tool(cap, cap, lambda _c=cap, _p=payload: core.run_capability(_c, _p))
                 for cap in core.capabilities()]
        agent = agents.Agent(name=args.agent, role=args.agent, tools=tools)
        task = agents.Task(description=args.capability)
        result = agent.execute(task, json.dumps(payload))
    else:
        result = core.run_capability(args.capability, payload)

    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
""")

