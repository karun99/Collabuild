MCP_SERVER = Template("""\"\"\"
$TITLE — Model Context Protocol (MCP) server.

Exposes the app's core capabilities as MCP tools over stdio JSON-RPC
(protocol subset: initialize, tools/list, tools/call). Connect from any MCP
client (Claude Desktop, Cursor, mcp CLI):

    mcp install server.py
    python server.py
\"\"\"

from __future__ import annotations

import json
import logging
import sys

import core

logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
log = logging.getLogger("mcp")

SERVER_NAME = "$PACKAGE"
VERSION = "1.0.0"

TOOLS = [
$MCP_TOOLS]


def _read_message() -> dict | None:
    line = sys.stdin.readline()
    if not line:
        return None
    try:
        return json.loads(line)
    except json.JSONDecodeError as exc:
        log.warning("invalid JSON-RPC frame: %s", exc)
        return None


def _write_message(msg: dict) -> None:
    sys.stdout.write(json.dumps(msg) + "\\n")
    sys.stdout.flush()


def _error(rid, code: int, message: str) -> dict:
    return {"jsonrpc": "2.0", "id": rid, "error": {"code": code, "message": message}}


def handle_request(req: dict) -> dict:
    rid = req.get("id")
    method = req.get("method", "")
    params = req.get("params") or {}

    if method == "initialize":
        return {
            "jsonrpc": "2.0",
            "id": rid,
            "result": {
                "protocolVersion": params.get("protocolVersion", "2024-11-05"),
                "capabilities": {"tools": {}},
                "serverInfo": {"name": SERVER_NAME, "version": VERSION},
            },
        }

    if method == "tools/list":
        return {"jsonrpc": "2.0", "id": rid, "result": {"tools": TOOLS}}

    if method == "tools/call":
        name = params.get("name", "")
        args = params.get("arguments") or {}
        for tool in TOOLS:
            if tool["name"] == name:
                output = core.run_capability(name, args)
                text = json.dumps(output, ensure_ascii=False)
                return {
                    "jsonrpc": "2.0",
                    "id": rid,
                    "result": {"content": [{"type": "text", "text": text}]},
                }
        return _error(rid, -32602, f"unknown tool: {name}")

    if method == "notifications/initialized":
        return {"jsonrpc": "2.0", "id": rid, "result": {}}

    return _error(rid, -32601, f"method not found: {method}")


def serve() -> int:
    log.info("%s MCP server ready", SERVER_NAME)
    while True:
        req = _read_message()
        if req is None:
            break
        try:
            response = handle_request(req)
        except Exception as exc:  # noqa: BLE001
            log.exception("request failed")
            response = _error(req.get("id"), -32603, str(exc))
        if response is not None:
            _write_message(response)
    return 0


if __name__ == "__main__":
    sys.exit(serve())
""")

