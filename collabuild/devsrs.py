"""DevSRS — SRS-driven application builder.

Consumes a drafted SRS document (IEEE 830-style markdown produced by the
pipeline's SRSGenerator stage) and materializes it into a real, runnable
application scaffold:

  * ``cli`` — a Python CLI application with an argparse entry point
  * ``web`` — a full-stack FastAPI application with a static single-page UI
  * ``mcp`` — a Model Context Protocol (MCP) server exposing the app's core
    capabilities as tools over stdio JSON-RPC

Every generated app embeds a lightweight multi-agent orchestration layer
(``agents.py``) modeled on LangChain agent runtimes and AutoGen conversational
agents, so the resulting application is agent-powered regardless of target.

Two build modes:

  * **Template mode** (default, offline): deterministic, runnable code is
    generated locally from the parsed SRS blueprint. Works without any API key.
  * **LLM mode** (``use_llm=True`` + a real provider): the configured LLM
    writes the ``core.py`` implementation guided by the SRS; the scaffolding
    shell always comes from the templates.

Usage::

    from collabuild.devsrs import DevSRS

    builder = DevSRS(target="web", output_dir="generated_app")
    result = builder.build(srs_text)

CLI: ``collabuild devsrs --srs-file SRS.md --target web --output ./app``
"""

